// Regenerates agent-templates.mjs: the generated plugin and extension sources
// the desktop writes for OpenCode, oh-my-pi and Amp (TEMPLATE in
// src-tauri/src/agents.rs) and the session context oh-my-pi carries
// (agent_instructions.rs SESSION_CONTEXT), so a cloud workspace installs
// byte-for-byte what the desktop does. agent-templates.test.mjs fails when the
// two drift; run `node gen-agent-templates.mjs` to refresh.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const here=path.dirname(fileURLToPath(import.meta.url));
const tauri=path.join(here,'..','..','src-tauri','src');

/** The `const TEMPLATE: &str = r#"…"#;` inside `fn <name>(`. */
export function rawTemplate(source,fn){
 const at=source.indexOf(`fn ${fn}(`);if(at<0)throw Error(`agents.rs has no fn ${fn}`);
 const open='const TEMPLATE: &str = r#"',start=source.indexOf(open,at);
 const next=source.indexOf('\nfn ',at+1);
 if(start<0||(next>=0&&start>next))throw Error(`fn ${fn} has no TEMPLATE`);
 const end=source.indexOf('"#;',start);return source.slice(start+open.length,end);
}
/** A plain Rust string literal's value (escapes and `\`-newline continuations). */
export function rustString(source,name){
 const open=`pub const ${name}: &str = "`,start=source.indexOf(open);if(start<0)throw Error(`no ${name}`);
 let out='',i=start+open.length;
 for(;;){
  const c=source[i];
  if(c==='"')return out;
  if(c!=='\\'){out+=c;i++;continue;}
  const e=source[i+1];
  if(e==='\n'){i+=2;while(/[ \t\n\r]/.test(source[i]))i++;continue;}
  out+={n:'\n',t:'\t',r:'\r','"':'"',"'":"'",'\\':'\\','0':'\0'}[e]??(()=>{throw Error(`escape \\${e}`);})();i+=2;
 }
}
export async function generate(){
 const agents=await readFile(path.join(tauri,'agents.rs'),'utf8'),instructions=await readFile(path.join(tauri,'agent_instructions.rs'),'utf8');
 const templates={opencode:rawTemplate(agents,'setup_opencode_plugin'),omp:rawTemplate(agents,'setup_omp_hook'),amp:rawTemplate(agents,'setup_amp_plugin'),sessionContext:rustString(instructions,'SESSION_CONTEXT')};
 return `// Generated by gen-agent-templates.mjs from src-tauri/src/agents.rs and\n// agent_instructions.rs. Do not edit by hand.\nexport const AGENT_TEMPLATES=${JSON.stringify(templates,null,1)};\n`;
}
if(process.argv[1]===fileURLToPath(import.meta.url))await writeFile(path.join(here,'agent-templates.mjs'),await generate());
