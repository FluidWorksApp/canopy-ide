// Clipboard commands for terminals on a workspace VM.
//
// A workspace terminal has `DISPLAY=:99` (the on-demand remote desktop), so a
// CLI that copies by shelling out to `xclip` — Cursor's agent, Aider through
// pyperclip, plain scripts — puts the text on a headless X server's clipboard
// that nobody can paste from. (Claude Code also runs xclip there, but writes
// OSC 52 itself as well.) These shims take the copy and send it the one way a
// program in a remote PTY can reach the clipboard of the computer showing the
// IDE: an OSC 52 sequence on its terminal, which Canopy's terminal turns into
// a clipboard write (src/terminalClipboard.ts, with its own input gating and
// 1 MiB cap).
//
// Only a copy to the CLIPBOARD selection becomes OSC 52. Reading the clipboard,
// non-text targets, and the PRIMARY selection go to the real tool when the image
// has one; otherwise a read finds nothing and a PRIMARY copy is dropped — tools
// commonly copy to both, and one clipboard write per copy is enough.
//
// The shims are installed by the runner at startup and put on PATH only for the
// PTYs it spawns; the remote desktop and its browser never see them.
import {chmod, mkdir, rename, rm, symlink, writeFile} from 'node:fs/promises';
import path from 'node:path';

export const CLIPBOARD_BIN = '/home/agent/.canopy/clipboard-bin';
export const CLIPBOARD_TOOLS = ['xclip', 'xsel', 'wl-copy', 'pbcopy'];
/** Matches the terminal's OSC 52 cap (OSC52_MAX_BYTES in terminalClipboard.ts):
 *  anything larger would be dropped on arrival, so it is refused here, where
 *  the program can still be told. */
export const CLIPBOARD_MAX_BYTES = 1024 * 1024;
const SCRIPT_NAME = 'canopy-clipboard';

export const CLIPBOARD_SHIM = String.raw`#!/bin/bash
# canopy-clipboard-shim: xclip, xsel, wl-copy and pbcopy for a Canopy workspace.
# A copy to the clipboard is sent to this terminal as OSC 52, which Canopy puts
# on the clipboard of the computer showing the IDE. Generated by
# packages/remote-host/clipboard-shims.mjs; edits here are overwritten.
max=${CLIPBOARD_MAX_BYTES}
name=${'$'}{0##*/}
here=$(cd -- "$(dirname -- "$0")" && pwd -P)

# The tool this shim stands in for, if the image has it: the first one on PATH
# that is not a shim.
real_tool() {
  local dir old=$IFS
  IFS=:
  for dir in $PATH; do
    [ -n "$dir" ] || continue
    [ "$(cd -- "$dir" 2>/dev/null && pwd -P)" = "$here" ] && continue
    if [ -f "$dir/$name" ] && [ -x "$dir/$name" ] && ! grep -q canopy-clipboard-shim "$dir/$name" 2>/dev/null; then
      IFS=$old; printf '%s\n' "$dir/$name"; return 0
    fi
  done
  IFS=$old; return 1
}

# Anything that is not a text copy to the clipboard: the real tool, or an empty
# clipboard (exit 1, as xclip -o says when there is nothing to paste).
delegate() {
  local tool
  if tool=$(real_tool); then exec "$tool" "$@"; fi
  exit 1
}

# A copy to a selection other than the clipboard: the real tool, or nothing.
not_clipboard() {
  local tool
  if tool=$(real_tool); then exec "$tool" "$@"; fi
  cat >/dev/null 2>&1
  exit 0
}

text_type() {
  case $1 in
    ''|text/plain*|UTF8_STRING|STRING|TEXT|COMPOUND_TEXT) return 0 ;;
    *) return 1 ;;
  esac
}

# copy TRIM FILTER [FILE...]: send stdin (or the files) to the terminal.
copy() {
  local trim=$1 filter=$2 tmp size b64
  shift 2
  tmp=$(mktemp "${'$'}{TMPDIR:-/tmp}/canopy-clipboard.XXXXXX") || exit 1
  trap 'rm -f "$tmp"' EXIT
  if [ $# -gt 0 ]; then
    cat -- "$@" | head -c $((max + 1)) >"$tmp" || exit 1
  else
    head -c $((max + 1)) >"$tmp"
  fi
  size=$(wc -c <"$tmp")
  if [ "$size" -gt "$max" ]; then
    echo "$name: Canopy copies at most 1 MiB to the desktop clipboard" >&2
    exit 1
  fi
  if [ -n "$trim" ] && [ "$size" -gt 0 ] && [ "$(tail -c 1 "$tmp" | od -An -tx1 | tr -d ' \n')" = 0a ]; then
    truncate -s -1 "$tmp"
    size=$((size - 1))
  fi
  [ -n "$filter" ] && cat "$tmp"
  [ "$size" -gt 0 ] || exit 0
  b64=$(base64 <"$tmp" | tr -d '\n')
  # The controlling terminal first. Under tmux that is a pane, so the sequence
  # goes in tmux's passthrough wrapper (inner ESCs doubled) to reach the real
  # terminal. A process with no controlling terminal falls back to the PTY the
  # session started on, which is Canopy's own, unwrapped.
  if { : >/dev/tty; } 2>/dev/null; then
    if [ -n "$TMUX" ]; then
      printf '\033Ptmux;\033\033]52;c;%s\007\033\\' "$b64" >/dev/tty
    else
      printf '\033]52;c;%s\007' "$b64" >/dev/tty
    fi
  elif [ -n "$CANOPY_TTY" ] && [ -w "$CANOPY_TTY" ]; then
    printf '\033]52;c;%s\007' "$b64" >"$CANOPY_TTY"
  else
    echo "$name: no terminal to send the copy to" >&2
    exit 1
  fi
}

xclip_main() {
  local mode=in selection=primary target='' filter='' trim='' files=()
  local args=("$@")
  while [ $# -gt 0 ]; do
    case $1 in
      -i|-in) mode=in ;;
      -o|-out) mode=out ;;
      -f|-filter) filter=1 ;;
      -r|-rmlastnl) trim=1 ;;
      -se|-sel|-sele|-selec|-select|-selecti|-selectio|-selection) shift; selection=$1 ;;
      -t|-target) shift; target=$1 ;;
      -l|-loops|-d|-display|-wait) shift ;;
      -h|-help|-version) delegate "${'$'}{args[@]}" ;;
      --) shift; files+=("$@"); break ;;
      -*) ;;
      *) files+=("$1") ;;
    esac
    shift
  done
  [ "$mode" = out ] && delegate "${'$'}{args[@]}"
  text_type "$target" || delegate "${'$'}{args[@]}"
  case $selection in
    c|cl|cli|clip|clipb|clipbo|clipboa|clipboar|clipboard) copy "$trim" "$filter" "${'$'}{files[@]}" ;;
    *) not_clipboard "${'$'}{args[@]}" ;;
  esac
}

xsel_main() {
  local mode='' selection=primary flag i
  local args=("$@")
  while [ $# -gt 0 ]; do
    case $1 in
      --input|--append|--follow) mode=in ;;
      --output) mode=out ;;
      --clear|--delete|--keep|--exchange|--help|--version) delegate "${'$'}{args[@]}" ;;
      --primary) selection=primary ;;
      --secondary) selection=secondary ;;
      --clipboard) selection=clipboard ;;
      --logfile|--display|--selectionTimeout|--windowName) shift ;;
      --*) ;;
      -*)
        flag=${'$'}{1#-}
        for ((i = 0; i < ${'$'}{#flag}; i++)); do
          case ${'$'}{flag:i:1} in
            i|a|f) mode=in ;;
            o) mode=out ;;
            c|d|k|x|h|v) delegate "${'$'}{args[@]}" ;;
            p) selection=primary ;;
            s) selection=secondary ;;
            b) selection=clipboard ;;
            l|t|w) shift; break ;;
          esac
        done ;;
    esac
    shift
  done
  # xsel's own default: input when stdin is not a terminal, else output.
  if [ -z "$mode" ]; then if [ -t 0 ]; then mode=out; else mode=in; fi; fi
  [ "$mode" = out ] && delegate "${'$'}{args[@]}"
  [ "$selection" = clipboard ] || not_clipboard "${'$'}{args[@]}"
  copy '' ''
}

wl_copy_main() {
  local selection=clipboard trim='' type='' words=() given=''
  local args=("$@")
  while [ $# -gt 0 ]; do
    case $1 in
      -p|--primary) selection=primary ;;
      -n|--trim-newline) trim=1 ;;
      -c|--clear) exit 0 ;;
      -t|--type) shift; type=$1 ;;
      --type=*) type=${'$'}{1#--type=} ;;
      -s|--seat) shift ;;
      -h|--help|-v|--version) delegate "${'$'}{args[@]}" ;;
      --) shift; words+=("$@"); given=1; break ;;
      -*) ;;
      *) words+=("$1"); given=1 ;;
    esac
    shift
  done
  text_type "$type" || delegate "${'$'}{args[@]}"
  [ "$selection" = clipboard ] || not_clipboard "${'$'}{args[@]}"
  # wl-copy copies its arguments, joined by spaces, when it is given any.
  if [ -n "$given" ]; then printf '%s' "${'$'}{words[*]}" | copy "$trim" ''; else copy "$trim" ''; fi
}

case $name in
  xclip) xclip_main "$@" ;;
  xsel) xsel_main "$@" ;;
  wl-copy) wl_copy_main "$@" ;;
  pbcopy) copy '' '' ;;
  *) echo "$name: not a clipboard command" >&2; exit 2 ;;
esac
`;

/** Write the shim and its four names into `dir`. Idempotent; the script is
 *  replaced atomically so a terminal mid-copy never runs half of it. */
export async function installClipboardShims(dir = CLIPBOARD_BIN) {
  await mkdir(dir, {recursive: true, mode: 0o755});
  const script = path.join(dir, SCRIPT_NAME), temp = `${script}.${process.pid}.tmp`;
  await writeFile(temp, CLIPBOARD_SHIM, {mode: 0o755});
  await chmod(temp, 0o755);
  await rename(temp, script);
  for (const tool of CLIPBOARD_TOOLS) {
    const link = path.join(dir, tool);
    await rm(link, {force: true});
    await symlink(SCRIPT_NAME, link);
  }
  return dir;
}
