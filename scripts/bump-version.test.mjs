import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm, copyFile, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync, execFileSync } from 'node:child_process';

// Runs the real scripts/bump-version.sh against a scratch repo with a bare
// local origin. Nothing is built and nothing leaves the machine: cargo and gh
// are fakes on PATH, and `npm version` only edits package.json.

const OLD = '0.5.14';
const NEW = '0.5.15';

const lock = (version) => `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "canopy-term-app"
version = "${version}"
dependencies = [
 "canopy-term-session",
]

[[package]]
name = "canopy-term-session"
version = "${OLD}"
`;

async function fixture({ termApp = OLD, termAppLock = termApp } = {}) {
  const base = await realpath(await mkdtemp(join(tmpdir(), 'canopy-bump-test-')));
  const repo = join(base, 'repo');
  const origin = join(base, 'origin.git');
  const tools = join(base, 'tools');
  await mkdir(join(repo, 'scripts'), { recursive: true });
  await mkdir(join(repo, 'src-tauri'));
  await mkdir(join(repo, 'crates/canopy-term-app'), { recursive: true });
  await mkdir(tools);
  await copyFile(new URL('./bump-version.sh', import.meta.url), join(repo, 'scripts/bump-version.sh'));
  await writeFile(join(repo, 'package.json'), JSON.stringify({ name: 'x', version: OLD }, null, 2) + '\n');
  await writeFile(join(repo, 'src-tauri/tauri.conf.json'), JSON.stringify({ version: OLD }, null, 2) + '\n');
  await writeFile(join(repo, 'src-tauri/Cargo.toml'), `[package]\nname = "app"\nversion = "${OLD}"\n\n[dependencies]\nfoo = { version = "1" }\n`);
  await writeFile(join(repo, 'src-tauri/Cargo.lock'), '');
  await writeFile(join(repo, 'crates/canopy-term-app/Cargo.toml'), `[package]\nname = "canopy-term-app"\nversion = "${termApp}"\n\n[dependencies]\nx = { version = "${termApp}" }\n`);
  await writeFile(join(repo, 'crates/canopy-term-app/Cargo.lock'), lock(termAppLock));
  // Fakes: cargo succeeds without doing anything; gh is unavailable.
  await writeFile(join(tools, 'cargo'), '#!/bin/sh\nexit 0\n', { mode: 0o755 });
  await writeFile(join(tools, 'gh'), '#!/bin/sh\nexit 1\n', { mode: 0o755 });
  const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', env: gitEnv() });
  function gitEnv() {
    return { ...process.env, GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t' };
  }
  execFileSync('git', ['init', '-q', '--bare', origin]);
  git(repo, 'init', '-q', '-b', 'main');
  git(repo, 'add', '-A');
  git(repo, 'commit', '-q', '-m', 'base');
  git(repo, 'remote', 'add', 'origin', origin);
  git(repo, 'push', '-q', 'origin', 'main');
  const run = (...args) =>
    spawnSync('bash', [join(repo, 'scripts/bump-version.sh'), ...args], {
      cwd: repo,
      encoding: 'utf8',
      env: { ...gitEnv(), PATH: tools + ':' + process.env.PATH },
    });
  return { base, repo, origin, git: (...a) => git(repo, ...a), run, read: (p) => readFile(join(repo, p), 'utf8') };
}

const manifestVersion = (text) => text.match(/^version = "([^"]+)"/m)[1];

test('a bump moves the terminal app manifest and its own lock entry with the release', async () => {
  const f = await fixture();
  try {
    const r = f.run(NEW);
    assert.equal(r.status, 0, r.stderr + r.stdout);
    assert.equal(f.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), `release/v${NEW}`);
    const manifest = await f.read('crates/canopy-term-app/Cargo.toml');
    assert.equal(manifestVersion(manifest), NEW);
    // Only [package]: a dependency that shares the old version is untouched.
    assert.match(manifest, new RegExp(`x = \\{ version = "${OLD}" \\}`));
    const l = await f.read('crates/canopy-term-app/Cargo.lock');
    assert.match(l, new RegExp(`name = "canopy-term-app"\\nversion = "${NEW}"`));
    // Another package in the lock that happens to be at the old version is not the app.
    assert.match(l, new RegExp(`name = "canopy-term-session"\\nversion = "${OLD}"`));
    // It is part of the release commit, which was pushed.
    assert.match(f.git('show', '--stat', '--format=', 'HEAD'), /crates\/canopy-term-app\/Cargo\.lock/);
    assert.match(f.git('--git-dir', f.origin, 'branch', '--list', `release/v${NEW}`), /release/);
  } finally {
    await rm(f.base, { recursive: true, force: true });
  }
});

test('--tag refuses when the terminal app manifest lags the release, naming it, and creates no tag', async () => {
  const f = await fixture({ termApp: OLD });
  try {
    // Everything else already at NEW, as on a merged release PR.
    await writeFile(join(f.repo, 'package.json'), JSON.stringify({ name: 'x', version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/tauri.conf.json'), JSON.stringify({ version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/Cargo.toml'), `[package]\nname = "app"\nversion = "${NEW}"\n`);
    f.git('commit', '-q', '-am', 'partial bump');
    f.git('push', '-q', 'origin', 'main');
    const r = f.run('--tag', NEW);
    assert.notEqual(r.status, 0);
    assert.match(r.stderr, /crates\/canopy-term-app\/Cargo\.toml is '0\.5\.14'/);
    assert.match(r.stderr, /crates\/canopy-term-app\/Cargo\.lock is '0\.5\.14'/);
    assert.equal(f.git('tag', '--list').trim(), '');
    assert.equal(f.git('--git-dir', f.origin, 'tag', '--list').trim(), '');
  } finally {
    await rm(f.base, { recursive: true, force: true });
  }
});

test('--tag refuses when only the terminal app lock lags', async () => {
  const f = await fixture({ termApp: NEW, termAppLock: OLD });
  try {
    await writeFile(join(f.repo, 'package.json'), JSON.stringify({ name: 'x', version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/tauri.conf.json'), JSON.stringify({ version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/Cargo.toml'), `[package]\nname = "app"\nversion = "${NEW}"\n`);
    f.git('commit', '-q', '-am', 'partial bump');
    f.git('push', '-q', 'origin', 'main');
    const r = f.run('--tag', NEW);
    assert.notEqual(r.status, 0);
    assert.match(r.stderr, /crates\/canopy-term-app\/Cargo\.lock is '0\.5\.14'/);
    assert.doesNotMatch(r.stderr, /Cargo\.toml is/);
    assert.equal(f.git('--git-dir', f.origin, 'tag', '--list').trim(), '');
  } finally {
    await rm(f.base, { recursive: true, force: true });
  }
});

test('--tag tags main when every file, including the terminal app, reads the release', async () => {
  const f = await fixture({ termApp: NEW });
  try {
    await writeFile(join(f.repo, 'package.json'), JSON.stringify({ name: 'x', version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/tauri.conf.json'), JSON.stringify({ version: NEW }, null, 2) + '\n');
    await writeFile(join(f.repo, 'src-tauri/Cargo.toml'), `[package]\nname = "app"\nversion = "${NEW}"\n`);
    f.git('commit', '-q', '-am', 'bump');
    f.git('push', '-q', 'origin', 'main');
    const r = f.run('--tag', NEW);
    assert.equal(r.status, 0, r.stderr + r.stdout);
    assert.equal(f.git('--git-dir', f.origin, 'tag', '--list').trim(), `v${NEW}`);
  } finally {
    await rm(f.base, { recursive: true, force: true });
  }
});

test('the checked-in terminal app already reads the version in package.json', async () => {
  const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
  const manifest = await readFile(new URL('../crates/canopy-term-app/Cargo.toml', import.meta.url), 'utf8');
  const l = await readFile(new URL('../crates/canopy-term-app/Cargo.lock', import.meta.url), 'utf8');
  assert.equal(manifestVersion(manifest), pkg.version);
  assert.match(l, new RegExp(`name = "canopy-term-app"\\nversion = "${pkg.version.replaceAll('.', '\\.')}"`));
});
