// Recomputes the SHA-256 pins for the preview browser's on-demand Chromium
// (packages/remote-host/browser-install.mjs) from playwright-core's
// browsers.json. Run after bumping playwright-core:
//
//   node scripts/pin-preview-chromium.mjs > packages/remote-host/browser-pins.json
//
// It streams each platform's archive from Playwright's CDN through SHA-256
// and keeps nothing on disk.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(new URL('../packages/remote-host/package.json', import.meta.url));
const browsers = JSON.parse(readFileSync(join(dirname(require.resolve('playwright-core/package.json')), 'browsers.json'), 'utf8')).browsers;
const shell = browsers.find(browser => browser.name === 'chromium-headless-shell');
const ffmpeg = browsers.find(browser => browser.name === 'ffmpeg');
const CDN = 'https://cdn.playwright.dev';
const PLATFORMS = {
  'mac-arm64': { shell: 'mac-arm64/chrome-headless-shell-mac-arm64.zip', ffmpeg: 'ffmpeg-mac-arm64.zip' },
  'mac-x64': { shell: 'mac-x64/chrome-headless-shell-mac-x64.zip', ffmpeg: 'ffmpeg-mac.zip' },
  'linux64': { shell: 'linux64/chrome-headless-shell-linux64.zip', ffmpeg: 'ffmpeg-linux.zip' },
  'linux-arm64': { shell: 'linux-arm64/chrome-headless-shell-linux-arm64.zip', ffmpeg: 'ffmpeg-linux-arm64.zip' },
  'win64': { shell: 'win64/chrome-headless-shell-win64.zip', ffmpeg: 'ffmpeg-win64.zip' },
};

async function hash(path) {
  const response = await fetch(`${CDN}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const digest = createHash('sha256');
  let bytes = 0;
  for await (const chunk of response.body) {
    digest.update(chunk);
    bytes += chunk.length;
  }
  return { sha256: digest.digest('hex'), bytes };
}

const files = {};
for (const [platform, names] of Object.entries(PLATFORMS)) {
  const shellPath = `builds/cft/${shell.browserVersion}/${names.shell}`;
  const ffmpegPath = `builds/ffmpeg/${ffmpeg.revision}/${names.ffmpeg}`;
  files[shellPath] = await hash(shellPath);
  files[ffmpegPath] = await hash(ffmpegPath);
  console.error(`${platform}: ${files[shellPath].bytes} + ${files[ffmpegPath].bytes} bytes`);
}
console.log(JSON.stringify({
  comment: 'Generated by scripts/pin-preview-chromium.mjs; do not edit.',
  browserVersion: shell.browserVersion,
  revision: shell.revision,
  ffmpegRevision: ffmpeg.revision,
  files,
}, null, 2));
